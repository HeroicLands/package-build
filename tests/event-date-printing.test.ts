const monthDays = [30, 31, 30, 31, 30, 31, 30, 30, 31, 30, 31, 30];
const monthNames = [
    "Lizelandi",
    "Lusenar",
    "Pozerandi",
    "Brazemandi",
    "Thumbandi",
    "Marendandi",
    "Elthezandi",
    "Karnavar",
    "Morvanandi",
    "Kalmethandi",
    "Zunelandi",
    "Kalpezandi",
];
const world = { fm: { type: "place", data: { year: { days: 365 } } } };

/** A calendar note whose `std` format is month and day numbers. */
function calendarNote(formats: Record<string, string>) {
    const fm = {
        type: "lore",
        subType: "calendar",
        shortcode: "commoncal",
        name: { full: "Common Calendar" },
        data: {
            epoch: "1.1",
            months: monthNames.map((name, i) => ({
                name,
                abbreviation: name.slice(0, 4),
                days: monthDays[i],
            })),
            formats,
            eras: [
                { shortcode: "bvr", name: "Before", abbreviation: "BF", start: null },
                { shortcode: "vr", name: "After", abbreviation: "AF", marker: "VR", start: 1 },
            ],
        },
    };
    return { file: "Calendar.md", raw: `---\n${YAML.stringify(fm)}---\n`, fm };
}

function context(notes: object[]) {
    return { ...resolveReckoningMarkers({ notes }, 365), daysPerYear: 365 } as any;
}

const dateOf = (written: string, dates: object) => parseNoteDate(written, dates).date;

describe("a calendar that sets no display format", () => {
    const numeric = context([world, calendarNote({ std: "MM/DD/Y GGG", long: "D MMMM Y GGG" })]);

    // The expected strings are the output of the engine at origin/main commit
    // 381c6e77, before `display` existed, for the calendar fixture above. They
    // were generated by extracting that commit's tree (`git archive 381c6e77`)
    // into a scratch directory, running the same infobox, `ref`, events
    // relation and `dateformat` calls on this fixture with that engine, and
    // copying the printed strings here. They are literals so the test does not
    // read another commit's engine.
    const golden: Array<[string, Record<string, string | null>]> = [
        [
            "709",
            {
                infobox: "709 AF",
                ref: "709",
                whenText: "709 AF",
                whenIn: "709 AF",
                dateformat: "709 AF",
            },
        ],
        [
            "709.120",
            {
                infobox: "04/29/709 AF",
                ref: "709.120",
                whenText: "04/29/709 AF",
                whenIn: "04/29/709 AF",
                dateformat: "04/29/709 AF",
            },
        ],
        [
            "709.120:143005",
            {
                infobox: "04/29/709 AF 14:30:05",
                ref: "709.120:143005",
                whenText: "04/29/709 AF 14:30:05",
                whenIn: "04/29/709 AF 14:30:05",
                dateformat: "04/29/709 AF 14:30:05",
            },
        ],
        [
            "~709.120",
            {
                infobox: "~04/29/709 AF",
                ref: "~709.120",
                whenText: "~04/29/709 AF",
                whenIn: "~04/29/709 AF",
                dateformat: "~04/29/709 AF",
            },
        ],
        [
            "~709.120:143005",
            {
                infobox: "~04/29/709 AF 14:30:05",
                ref: "~709.120:143005",
                whenText: "~04/29/709 AF 14:30:05",
                whenIn: "~04/29/709 AF 14:30:05",
                dateformat: "~04/29/709 AF 14:30:05",
            },
        ],
        [
            "datefrom commoncal 04/709 AF",
            {
                infobox: "04/709 AF",
                ref: "04/709 AF",
                whenText: "04/709 AF",
                whenIn: "04/709 AF",
                dateformat: null,
            },
        ],
        [
            "-5.120",
            {
                infobox: "04/29/5 BF",
                ref: "-5.120",
                whenText: "04/29/5 BF",
                whenIn: "04/29/5 BF",
                dateformat: "04/29/5 BF",
            },
        ],
    ];

    it.each(golden)("prints %s on every surface as it always has", (written, expected) => {
        const date = dateOf(written, numeric);
        const fm = {
            type: "being",
            name: { full: "Henwo" },
            data: { died: written, born: written, calendar: "commoncal" },
        };
        const rows = noteInfobox(fm, { dates: numeric }).sections[0].rows;
        const record = {
            package: "thalorna",
            type: "lore",
            shortcode: "siege",
            resolvedCalendar: "commoncal",
            data: { events: [{ when: written }] },
            resolvedDates: { events: [{ when: date }] },
        };
        const [row] = eventRows([record], numeric, ["commoncal"]);
        expect(rows.find((each: any) => each.label === "Died")?.value).toBe(expected.infobox);
        expect(rows.find((each: any) => each.label === "Born")?.value).toBe(expected.infobox);
        expect(
            eventFieldText({ entry: { when: written }, when: date }, "when", numeric, "commoncal"),
        ).toEqual({
            text: expected.ref,
        });
        expect(row.whenText).toBe(expected.whenText);
        expect(row.whenIn.commoncal).toBe(expected.whenIn);
        expect(printEventDateIn(written, date, numeric, "commoncal")).toBe(expected.whenIn);
        if (expected.dateformat !== null)
            expect(
                renderMarkdownExpressions(`{{dateformat "commoncal" "${written}"}}`, {
                    dates: numeric,
                }).markdown,
            ).toBe(expected.dateformat);
    });

    it("keeps a std that names the month", () => {
        const named = context([world, calendarNote({ std: "D MMM Y GGG" })]);
        const date = dateOf("709.120", named);
        expect(printEventDateIn("709.120", date, named, "commoncal")).toBe("29 Braz 709 AF");
    });

    it("prints no index prose", () => {
        const fm = { type: "being", name: { full: "Henwo" }, data: { died: "709.120" } };
        expect(resolvedDateFields(fm, numeric).died.prose).toBeNull();
    });
});

describe("a page with no calendar", () => {
    const bare = context([world]);

    // Each row is the date, what the engine at commit 381c6e77 printed for it
    // on every surface when no calendar resolves, and what it prints now. A day
    // is the only shape that differs.
    const rows: Array<[string, string, string]> = [
        ["709", "709", "709"],
        ["709.120", "709.120", "day 120 of 709"],
        ["709.120:143005", "709.120:143005", "day 120 of 709 14:30:05"],
        ["~709.120", "~709.120", "~day 120 of 709"],
        ["-5.120", "-5.120", "day 120 of year -5"],
    ];

    it.each(rows)(
        "prints %s as a plain year and day, and a year as the year",
        (written, before, now) => {
            const date = dateOf(written, bare);
            const fm = { type: "being", name: { full: "Henwo" }, data: { died: written } };
            const infobox = noteInfobox(fm, { dates: bare }).sections[0].rows.find(
                (each: any) => each.label === "Died",
            )?.value;
            const record = {
                package: "thalorna",
                type: "lore",
                shortcode: "siege",
                data: { events: [{ when: written }] },
                resolvedDates: { events: [{ when: date }] },
            };
            const [row] = eventRows([record], bare, []);
            const ref = eventFieldText(
                { entry: { when: written }, when: date },
                "when",
                bare,
                undefined,
            );
            const prose = renderMarkdownExpressions(`{{dateformat "${written}"}}`, {
                dates: bare,
                fm,
            });
            expect([infobox, row.whenText, ref.text, prose.markdown]).toEqual([now, now, now, now]);
            expect(now === before).toBe(written === "709");
        },
    );
});

describe("a calendar that sets a display format", () => {
    const numeric = context([
        world,
        calendarNote({ std: "MM/DD/Y GGG", long: "D MMMM Y GGG", display: "MMMM D, Y GGG" }),
    ]);
    const print = (written: string, dates: any = numeric) =>
        printEventDateIn(written, dateOf(written, dates), dates, "commoncal");

    it("prints each date shape in the display format", () => {
        expect(print("709.120")).toBe("Brazemandi 29, 709 AF");
        expect(print("709.120:143005")).toBe("Brazemandi 29, 709 AF 14:30:05");
        expect(print("~709.120")).toBe("~Brazemandi 29, 709 AF");
        expect(print("709")).toBe("709 AF");
        expect(print("-5.120")).toBe("Brazemandi 29, 5 BF");
        expect(print("710.31")).toBe("Lusenar 1, 710 AF");
        expect(print("datefrom commoncal 04/709 AF")).toBe("Brazemandi, 709 AF");
    });

    it("prints month and day numbers when the author sets them", () => {
        const set = context([world, calendarNote({ std: "MM/DD/Y GGG", display: "DD.MM.Y GGG" })]);
        expect(print("709.120", set)).toBe("29.04.709 AF");
    });

    it("still reads dates in std", () => {
        expect(dateOf("datefrom commoncal 04/29/709 AF", numeric)).toMatchObject({
            canonicalYear: 709,
            canonicalDay: 120,
        });
    });

    it("prints the same date on the event, infobox, dateformat, ref and relation surfaces", () => {
        const date = dateOf("709.120", numeric);
        const event = printEventDateIn("709.120", date, numeric, "commoncal");
        const fm = {
            type: "being",
            name: { full: "Henwo" },
            data: { died: "709.120", calendar: "commoncal" },
        };
        const rows = noteInfobox(fm, { dates: numeric }).sections[0].rows;
        const infobox = rows.find((row: any) => row.label === "Died")?.value;
        const prose = renderMarkdownExpressions('{{dateformat "commoncal" "709.120"}}', {
            dates: numeric,
        }).markdown;
        const ref = eventFieldText(
            { entry: { when: "709.120" }, when: date },
            "when",
            numeric,
            "commoncal",
        );
        const record = {
            package: "thalorna",
            type: "lore",
            shortcode: "siege",
            data: { events: [{ when: "709.120", until: "710.31" }] },
            resolvedDates: { events: [{ when: date, until: dateOf("710.31", numeric) }] },
        };
        const [row] = eventRows([record], numeric, ["commoncal"]);
        const written = "datefrom commoncal 04/29/709 AF";
        const born = resolvedDateFields(
            { type: "being", name: { full: "Henwo" }, data: { died: written } },
            numeric,
        );
        const indexed = resolvedDateFields(
            { type: "place", data: { events: [{ when: written }] } },
            numeric,
        );
        expect(born.died.prose).toBe(event);
        expect(indexed.events[0].when.prose).toBe(event);
        expect(event).toBe("Brazemandi 29, 709 AF");
        expect(infobox).toBe(event);
        expect(prose).toBe(event);
        expect(ref).toEqual({ text: event });
        expect(row.whenIn.commoncal).toBe(event);
        expect(row.untilIn.commoncal).toBe("Lusenar 1, 710 AF");
    });

    it("uses a named format exactly as written", () => {
        const named = (format: string) =>
            renderMarkdownExpressions(`{{dateformat "commoncal" "709.120" "${format}"}}`, {
                dates: numeric,
            }).markdown;
        expect(named("std")).toBe("04/29/709 AF");
        expect(named("long")).toBe("29 Brazemandi 709 AF");
    });
});

describe("a display format in a calendar note", () => {
    const note = calendarNote({ std: "MM/DD/Y GGG", display: "D MMMM Y GGG [moon]" });
    const check = (formats: Record<string, string>) => {
        const each = calendarNote(formats);
        return checkCalendarNote(each, { index: { notes: [world, each] } } as never);
    };

    it("is accepted when it prints", () => {
        expect(check({ std: "MM/DD/Y GGG", display: "MMMM D, Y GGG" })).toEqual([]);
    });

    it("is reported at its key when it needs runtime data", () => {
        const findings = checkCalendarNote(note, { index: { notes: [world, note] } } as never);
        expect(findings).toHaveLength(1);
        const line =
            note.raw.split("\n").findIndex((each: string) => each.includes("display:")) + 1;
        expect(findings[0]).toMatchObject({ severity: "error", file: "Calendar.md", line });
        expect(findings[0].column).toBeGreaterThan(0);
        expect(findings[0].message).toContain("moon");
    });

    it("is never the format dates are read in", () => {
        expect(check({ display: "MMMM D, Y GGG" })).toEqual([]);
    });
});

describe("event dates without a calendar", () => {
    const bare = context([world]);

    it("prints a year and day as a plain year and day", () => {
        const date = dateOf("709.120", bare);
        expect(printEventDateIn("709.120", date, bare, "commoncal")).toBe("day 120 of 709");
        expect(printEventDateIn("709.120", date, bare, undefined)).toBe("day 120 of 709");
        expect(printEventDate("709.120", date, bare)).toBe("709.120");
        expect(printEventDate("709.120", date, bare, { plain: true })).toBe("day 120 of 709");
    });

    it("prints a reference to a date with no page calendar as a plain year and day", () => {
        const date = dateOf("709.120", bare);
        expect(
            eventFieldText({ entry: { when: "709.120" }, when: date }, "when", bare, undefined),
        ).toEqual({ text: "day 120 of 709" });
    });

    it("names a negative year as a year", () => {
        const date = dateOf("-5.120", bare);
        expect(printEventDateIn("-5.120", date, bare, undefined)).toBe("day 120 of year -5");
    });

    it("keeps the clock and the approximate mark", () => {
        const timed = dateOf("~709.120:143005", bare);
        expect(printEventDateIn("~709.120:143005", timed, bare, undefined)).toBe(
            "~day 120 of 709 14:30:05",
        );
    });

    it("prints a year-only date as the year", () => {
        const date = dateOf("709", bare);
        expect(printEventDateIn("709", date, bare, undefined)).toBe("709");
    });

    it("prints an unresolved date as written", () => {
        expect(printEventDateIn("sometime", null, bare, undefined)).toBe("sometime");
    });
});
